/// `clock_facts`: two asynchronous domains share the one generated reset
/// port (ADR-0065 R5).
#[test]
fn rdc_shared_async_reset_is_e3003_with_an_aliased_clock() {
    let template = "domain Fast {
    clock = posedge
    reset = async active_low
}
domain Slow {
    clock = posedge
    reset = async active_low
}
module Bridge {
    in  fast_clk  : {CLK} @Fast
    in  slow_clk  : {CLK} @Slow
    in  fast_in   : bool  @Fast
    out fast_seen : bool  @Fast
    out slow_out  : bool  @Slow
    reg(fast_clk) seen : bool = false
    on fast_clk {
        seen <= fast_in
    }
    fast_seen = seen
    slow_out = sync(fast_in, slow_clk)
}
";
    same_in_every_form("rdc-shared", template, &["E3003"]);
}

