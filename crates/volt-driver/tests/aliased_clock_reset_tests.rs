//! A clock or reset port written through a type alias is the same port as
//! one written with `clock` or `reset(...)` (#234).
//!
//! ADR-0070 §6: "`type C = clock` ... and chains (`type V = W`) work like
//! the type itself in a port". So every design below is compiled three
//! times, with the same line count: the port types written directly, through
//! one alias, and through a chain of two aliases. `volt build --single-file
//! --emit=sva,sdc` must give the same diagnostic codes, the same exit code
//! and byte-identical output files (SV, SVA, SDC) in all three forms; the
//! expected codes of the direct form come from the specification, by hand.
//!
//! Each test names the place that classified ports by their syntax before
//! the fix (the inventory of #407, `docs/design/tek-yerde-bilgi-envanteri.md`
//! §3); the place now reads the class from the type checker
//! (`volt_hir::port_class`) or, before type checking, from the alias chain
//! (`volt_ast::alias::signal_class`).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Clone, Copy, Debug)]
enum Form {
    Direct,
    Alias,
    Chain,
}

const FORMS: [Form; 3] = [Form::Direct, Form::Alias, Form::Chain];

/// `{CLK}` and `{RST:<kind>}` in `template` written in `form`. The prelude
/// has one line per alias of the chain form in every form, so the source
/// line numbers that the SVA comments carry are the same.
fn render(template: &str, form: Form) -> String {
    let mut prelude = Vec::new();
    let mut body = template.to_string();
    let alias = |target: String, name: &str, prelude: &mut Vec<String>| -> String {
        match form {
            Form::Direct => {
                prelude.push(String::new());
                prelude.push(String::new());
                target
            }
            Form::Alias => {
                prelude.push(format!("type {name} = {target}"));
                prelude.push(String::new());
                name.to_string()
            }
            Form::Chain => {
                prelude.push(format!("type {name}Base = {target}"));
                prelude.push(format!("type {name} = {name}Base"));
                name.to_string()
            }
        }
    };
    if body.contains("{CLK}") {
        let ty = alias("clock".to_string(), "Clk", &mut prelude);
        body = body.replace("{CLK}", &ty);
    }
    let mut n = 0;
    while let Some(start) = body.find("{RST:") {
        let end = start + body[start..].find('}').expect("closing brace");
        let kind = body[start + 5..end].to_string();
        let ty = alias(format!("reset({kind})"), &format!("Rst{n}"), &mut prelude);
        body = body.replace(&format!("{{RST:{kind}}}"), &ty);
        n += 1;
    }
    format!("{}\n{body}", prelude.join("\n"))
}

fn temp_dir(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("volt-alias-clock-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("temp dir");
    dir
}

/// Every file under `dir`, by relative path, without the version header
/// line (`// Generated by Volt <version>`, `# Generated by Volt ...`).
fn files(dir: &Path) -> BTreeMap<String, String> {
    fn walk(base: &Path, dir: &Path, out: &mut BTreeMap<String, String>) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(base, &p, out);
            } else {
                let rel = p
                    .strip_prefix(base)
                    .unwrap()
                    .to_string_lossy()
                    .replace('\\', "/");
                let text = std::fs::read_to_string(&p).unwrap_or_default();
                let kept: Vec<&str> = text
                    .lines()
                    .filter(|l| !l.contains("Generated by Volt"))
                    .collect();
                out.insert(rel, kept.join("\n"));
            }
        }
    }
    let mut out = BTreeMap::new();
    walk(dir, dir, &mut out);
    out
}

/// The error and warning codes of a human-format report, sorted.
fn codes(stderr: &str) -> Vec<String> {
    let mut out = Vec::new();
    for head in ["error[", "warning["] {
        let mut rest = stderr;
        while let Some(i) = rest.find(head) {
            let code = &rest[i + head.len()..];
            if let Some(end) = code.find(']') {
                out.push(code[..end].to_string());
            }
            rest = &rest[i + head.len()..];
        }
    }
    out.sort();
    out
}

struct Build {
    exit: Option<i32>,
    codes: Vec<String>,
    stderr: String,
    files: BTreeMap<String, String>,
}

fn build(tag: &str, src: &str) -> Build {
    let dir = temp_dir(tag);
    std::fs::write(dir.join("t.volt"), src).expect("write source");
    let out = Command::new(env!("CARGO_BIN_EXE_volt"))
        .current_dir(&dir)
        .args([
            "build",
            "t.volt",
            "--color=never",
            "--single-file",
            "--emit=sva,sdc",
            "--target-dir",
            "out",
        ])
        .env_remove("VOLT_LANG")
        .output()
        .expect("volt runs");
    let stderr =
        String::from_utf8_lossy(&out.stderr).into_owned() + &String::from_utf8_lossy(&out.stdout);
    let result = Build {
        exit: out.status.code(),
        codes: codes(&stderr),
        stderr,
        files: files(&dir.join("out")),
    };
    let _ = std::fs::remove_dir_all(&dir);
    result
}

/// Builds `template` in the three forms: the direct form gives `expected`
/// (sorted codes, from the specification), and the other two the same
/// exit code, codes and files. Returns the direct form's build.
fn same_in_every_form(tag: &str, template: &str, expected: &[&str]) -> Build {
    let builds: Vec<(Form, Build)> = FORMS
        .iter()
        .map(|&f| (f, build(&format!("{tag}-{f:?}"), &render(template, f))))
        .collect();
    let (_, direct) = &builds[0];
    let mut want: Vec<String> = expected.iter().map(|c| c.to_string()).collect();
    want.sort();
    assert_eq!(direct.codes, want, "direct form:\n{}", direct.stderr);
    for (form, b) in &builds[1..] {
        assert_eq!(
            (b.exit, &b.codes),
            (direct.exit, &direct.codes),
            "{form:?} form differs from the direct form:\n{}\n--- source:\n{}",
            b.stderr,
            render(template, *form)
        );
        assert_eq!(
            b.files.keys().collect::<Vec<_>>(),
            direct.files.keys().collect::<Vec<_>>(),
            "{form:?} form writes other files:\n{}",
            b.stderr
        );
        for (path, text) in &b.files {
            assert_eq!(
                text, &direct.files[path],
                "{form:?} form: {path} differs from the direct form"
            );
        }
    }
    builds.into_iter().next().unwrap().1
}

