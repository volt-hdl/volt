// ═══ Timing constraints (ADR-0054): constraints/walk.rs ═══════════════

const UART: &str = "domain Sys {
    clock = posedge,
    reset = sync active_high,
    frequency = 50.mhz,
}
@timing(clk >= 40.mhz)
@false_path(from = cfg_r, to = sample)
pub module Uart {
    in  clk    : {CLK} @Sys
    in  rx     : bool
    in  cfg    : u8
    in  cfg_we : bool
    out sample : bool
    out level  : u8
    reg cfg_r    : u8 = 0
    reg count_r  : u8 = 0
    reg sample_r : bool = false
    on clk {
        if cfg_we {
            cfg_r <= cfg
        }
        if count_r == cfg_r {
            count_r  <= 0
            sample_r <= rx
        } else {
            count_r <= count_r + 1
        }
    }
    sample = sample_r
    level  = cfg_r
}
";

/// `Scope::new`: the frequency of domain Sys (50 MHz) gives the period
/// 20.000 ns of `create_clock` (ADR-0054), and `@timing(clk >= 40.mhz)`
