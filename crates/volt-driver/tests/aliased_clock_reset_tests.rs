/// The extern gets the raw reset while the module's registers on the same
/// clock leave reset through the synchronizer (#93). Also the reset
/// binding rule of the type checker (E2003, `typeck/reset_binding.rs`):
/// `rst: rst` binds a raw reset port.
#[test]
fn rdc_raw_reset_into_an_extern_is_w3011_with_aliased_ports() {
    let template = "extern module RisePulse {
    in  clk   : {CLK}
    in  rst   : {RST:sync, active_high}
    in  level : bool
    out rise  : bool
}
module ExternRawReset {
    in  clk    : {CLK}
    in  rst    : {RST:sync, active_high}
    in  button : bool
    out count  : u8
    let det = RisePulse { clk: clk, rst: rst, level: button }
    reg count_r : u8 = 0
    on clk {
        if det.rise {
            count_r <= count_r + 1
        }
    }
    count = count_r
}
";
    same_in_every_form("rdc-extern", template, &["W0022", "W3011"]);
}

/// A raw reset port that matches its domain: no diagnostic (the release
/// synchronizer reads it, so it is not an unused input, W1001), and the
