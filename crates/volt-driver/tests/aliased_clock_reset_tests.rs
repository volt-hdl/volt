// ═══ L1 timing (ADR-0037): timing.rs ══════════════════════════════════

/// `ModuleTiming::run`: a clock carries no timing, so `sync(s1, b_clk)`
/// does not combine a 1-cycle value with a 0-cycle one; `s1 + s2` does
/// (1 and 2 cycles old: E5010). The shared synchronous reset of the two
/// clocks is W3010 (ADR-0065 R5'); the 32-bit value through `sync` W3003.
#[test]
fn l1_timing_reports_e5010_and_not_on_an_aliased_clock() {
    let template = "domain A {
    clock = posedge
}
domain B {
    clock = posedge
}
@strict_timing
module Top {
    in  a_clk : {CLK} @A
    in  b_clk : {CLK} @B
    in  x     : u32 @A
    out y     : u32 @B
    out z     : u32 @A
    reg s1 : Delayed<u32, 1> = 0
    reg s2 : Delayed<u32, 2> = 0
    on a_clk {
        s1 <= x
        s2 <= s1
    }
    let s = sync(s1, b_clk)
    reg(b_clk) r : u32 = 0
    on b_clk {
        r <= s
    }
    y = r
    z = s1 + s2
}
";
    let direct = same_in_every_form("l1", template, &["E5010", "W3003", "W3010"]);
    assert!(direct.stderr.contains("z = s1 + s2"), "{}", direct.stderr);
}

