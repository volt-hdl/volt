/// The automatic FSM contracts (ADR-0066) of a module with an aliased
/// clock.
#[test]
fn automatic_contracts_of_a_module_with_an_aliased_clock() {
    let template = "enum S { Idle, Run, Done }
module Fsm {
    in  clk  : {CLK}
    in  go   : bool
    out busy : bool
    reg st : S = S::Idle
    on clk {
        match st {
            S::Idle => { if go { st <= S::Run } }
            S::Run  => { st <= S::Done }
            S::Done => { st <= S::Idle }
        }
    }
    busy = st == S::Run
}
";
    let direct = same_in_every_form("fsm", template, &["W0022"]);
    let sva = &direct.files["formal/fsm.sva"];
    assert!(sva.contains("auto FSM state valid"), "{sva}");
}
