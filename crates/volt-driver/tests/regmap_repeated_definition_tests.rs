//! `volt check-regmap` ve aynı adın birden çok tanımı (#374, ADR-0063 §3).
//!
//! Başka bir Volt sürümünün ürettiği dosyada erişimci gövdeleri
//! karşılaştırılmaz, görünüm yine tam karşılaştırılır. İki boşluk vardı:
//! C başlığında bir makronun yeniden tanımı (ayrıştırıcı ilk tanımı,
//! C önişlemcisi genişlettiği yerde yürürlükteki tanımı alır) ve JSON'da
//! aynı adla ikinci bir register (adla eşleme onu görmüyordu). İkisi de
//! "Match" ve çıkış 0 veriyordu.
//!
//! Tasarım: `tests/ui/pass/72_mmio_driver_generation.volt` (`PwmRegs`, beş
//! register: 0x00–0x10; RTL yalnız bu beş adresi çözer).

mod tools;

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use tools::Tool;

fn volt() -> Command {
    Command::new(env!("CARGO_BIN_EXE_volt"))
}

fn design() -> PathBuf {
    PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."))
        .join("tests/ui/pass/72_mmio_driver_generation.volt")
}

fn temp_dir(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("volt-regmap-dup-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("temp dizini");
    dir
}

fn text_of(o: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    )
}

/// `volt build --emit=c,regmap` → `<dir>/sw`.
fn generate(dir: &Path) -> PathBuf {
    let o = volt()
        .args(["--lang", "en", "build", "--emit=c,regmap", "--target-dir"])
        .arg(dir)
        .arg(design())
        .output()
        .expect("volt çalışmalı");
    assert_eq!(o.status.code(), Some(0), "{}", text_of(&o));
    dir.join("sw")
}

/// Başlığın imza satırı başka bir Volt sürümünü söyler (`regmap-hash`
/// satırı aynı kalır): erişimci kodu karşılaştırılmaz.
fn other_version_header(sw: &Path) -> String {
    let text = std::fs::read_to_string(sw.join("pwm_regs.h")).unwrap();
    let (first, rest) = text.split_once('\n').unwrap();
    assert!(first.starts_with("// Generated by Volt "), "{first}");
    let source = first.split_once(" from ").unwrap().1;
    format!("// Generated by Volt 0.0.9 from {source}\n{rest}")
}

/// `DUTY`'nin adres makrosu erişimcilerinden önce 0x14'e yeniden tanımlanır
/// (issue'daki başlık).
fn redefine_duty(header: &str) -> String {
    let anchor = "#define PWM_REGS_DUTY_RESET 0x00000000U\n";
    assert_eq!(header.matches(anchor).count(), 1, "{header}");
    header.replacen(
        anchor,
        &format!("{anchor}#undef PWM_REGS_DUTY\n#define PWM_REGS_DUTY (PWM_REGS_BASE + 0x14U)\n"),
        1,
    )
}

fn check_regmap(file: &Path, json: bool) -> Output {
    let mut cmd = volt();
    cmd.args(["--lang", "en", "check-regmap"]);
    if json {
        cmd.args(["--format", "json"]);
    }
    cmd.arg(design())
        .arg("--against")
        .arg(file)
        .output()
        .expect("volt çalışmalı")
}

/// `--format json` çıktısındaki tek dosyanın ayrışma kalemleri:
/// (tür, konu, dosya değeri).
fn drift(o: &Output) -> Vec<(String, String, String)> {
    let v: serde_json::Value = serde_json::from_slice(&o.stdout)
        .unwrap_or_else(|e| panic!("JSON olmalı ({e}): {}", text_of(o)));
    v["regmap_check"]["files"][0]["drift"]
        .as_array()
        .unwrap()
        .iter()
        .map(|d| {
            (
                d["kind"].as_str().unwrap_or_default().to_string(),
                d["subject"].as_str().unwrap_or_default().to_string(),
                d["file"].as_str().unwrap_or_default().to_string(),
            )
        })
        .collect()
}

#[test]
fn old_version_header_that_redefines_a_register_address_is_e9003() {
    let dir = temp_dir("h");
    let sw = generate(&dir);
    let file = dir.join("pwm_regs.h");
    std::fs::write(&file, redefine_duty(&other_version_header(&sw))).unwrap();
    let o = check_regmap(&file, false);
    let text = text_of(&o);
    assert_eq!(o.status.code(), Some(1), "{text}");
    assert!(text.contains("E9003"), "{text}");
    assert!(!text.contains("Match pwm_regs.h"), "{text}");
    let items = drift(&check_regmap(&file, true));
    assert!(
        items.contains(&(
            "offset".to_string(),
            "PWM_REGS_DUTY".to_string(),
            "0x14".to_string()
        )),
        "görünüm son tanımı okur: {items:#?}"
    );
    assert!(
        items
            .iter()
            .any(|(k, s, _)| k == "inconsistent" && s == "PWM_REGS_DUTY"),
        "{items:#?}"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn old_version_json_that_repeats_a_register_name_is_e9003() {
    let dir = temp_dir("json");
    let sw = generate(&dir);
    let mut v: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(sw.join("pwm_regs.json")).unwrap()).unwrap();
    v["generator"] = serde_json::json!("volt 0.0.9");
    let base = v["base"].as_u64().unwrap();
    let regs = v["registers"].as_array_mut().unwrap();
    let mut duty = regs
        .iter()
        .find(|r| r["name"] == "duty")
        .expect("duty register'ı")
        .clone();
    duty["offset"] = serde_json::json!(0x14);
    duty["address"] = serde_json::json!(base + 0x14);
    duty["access"] = serde_json::json!("ro");
    regs.push(duty);
    let file = dir.join("pwm_regs.json");
    std::fs::write(&file, serde_json::to_string_pretty(&v).unwrap()).unwrap();
    let o = check_regmap(&file, false);
    let text = text_of(&o);
    assert_eq!(o.status.code(), Some(1), "{text}");
    assert!(text.contains("E9003"), "{text}");
    assert_eq!(
        drift(&check_regmap(&file, true)),
        vec![(
            "inconsistent".to_string(),
            "PWM_REGS_DUTY".to_string(),
            "register DUTY is declared twice (offset 0x04, then 0x14)".to_string()
        )]
    );
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn check_regmap_reads_the_address_the_c_compiler_uses() {
    // Davranış: başlığı içeren bir C programının gördüğü DUTY adresi,
    // check-regmap'in dosya için bildirdiği offset'tir.
    let Some(cc) = tools::require(Tool::Cc) else {
        return;
    };
    let dir = temp_dir("cc");
    let sw = generate(&dir);
    std::fs::write(
        dir.join("pwm_regs.h"),
        redefine_duty(&other_version_header(&sw)),
    )
    .unwrap();
    std::fs::write(
        dir.join("main.c"),
        "#include <stdio.h>\n#include \"pwm_regs.h\"\nint main(void) {\n    printf(\"0x%02lX\\n\", (unsigned long)(PWM_REGS_DUTY - PWM_REGS_BASE));\n    return 0;\n}\n",
    )
    .unwrap();
    let exe = dir.join(if cfg!(windows) { "duty.exe" } else { "duty" });
    let o = Command::new(&cc)
        .args(["-std=c99", "-o"])
        .arg(&exe)
        .arg(dir.join("main.c"))
        .current_dir(&dir)
        .output()
        .expect("derleyici çalışmalı");
    assert!(o.status.success(), "{}", text_of(&o));
    let run = Command::new(&exe).output().expect("program çalışmalı");
    assert!(run.status.success(), "{}", text_of(&run));
    let compiled = String::from_utf8_lossy(&run.stdout).trim().to_string();
    assert_eq!(compiled, "0x14", "C önişlemcisi son tanımı kullanır");
    let items = drift(&check_regmap(&dir.join("pwm_regs.h"), true));
    let reported: Vec<&str> = items
        .iter()
        .filter(|(k, s, _)| k == "offset" && s == "PWM_REGS_DUTY")
        .map(|(_, _, f)| f.as_str())
        .collect();
    assert_eq!(reported, [compiled.as_str()], "{items:#?}");
    let _ = std::fs::remove_dir_all(&dir);
}
