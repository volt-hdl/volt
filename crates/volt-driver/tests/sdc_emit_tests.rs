#[test]
fn vga_example_two_clocks_groups_and_cdc_false_paths() {
    let (target, out) = build("vga", &root().join("examples/vga/vga_top.volt"), "sdc");
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "stderr: {stderr}");
    let top = read(&target.join("constraints/VgaTop.sdc"));
    assert_eq!(top.matches("create_clock").count(), 2, "{top}");
    assert!(
        top.contains("create_clock -name sys_clk -period 10.000 [get_ports sys_clk]"),
        "{top}"
    );
    assert!(
        top.contains("create_clock -name pix_clk -period 39.722 [get_ports pix_clk]"),
        "{top}"
    );
    assert!(top.contains("set_clock_groups -asynchronous"), "{top}");
    // frame_buffer: AsyncDualPortRam alt modül örneğinde, önekli.
    assert!(top.contains("set_false_path -from [get_cells {fb/mem_mem_reg*}] -to [get_cells {fb/mem_rd_data_reg*}]"), "{top}");
    // sync() köprüleri: invert (port, yakalama register'ı), done_r (reg), vs_active (let → pix_clk).
    assert!(
        top.contains("-to [get_cells {sync_invert_stage0_reg*}]"),
        "{top}"
    );
    assert!(top.contains("set_false_path -from [get_cells {done_r_reg*}] -to [get_cells {sync_done_r_stage0_reg*}]"), "{top}");
    assert!(top.contains("set_false_path -from [get_clocks pix_clk] -to [get_cells {sync_vs_active_stage0_reg*}]"), "{top}");
    // VgaTiming: @timing(pix_clk >= 25_175.khz) alan frekansıyla karşılanır.
    let timing = read(&target.join("constraints/VgaTiming.sdc"));
    assert!(
        timing.contains("create_clock -name pix_clk -period 39.722 [get_ports pix_clk]"),
        "{timing}"
    );
    assert!(
        !stderr.contains("W0021"),
        "@timing artık W0021 üretmez: {stderr}"
    );
    assert!(!stderr.contains("W0022"), "{stderr}");
    let _ = std::fs::remove_dir_all(&target);
}

#[test]
fn domain_without_frequency_warns_w0022_only_when_sdc_requested() {
    let dir = temp_dir("w0022");
    let src = "domain Sys { clock = posedge }\nmodule M {\n    in clk : clock @Sys\n    in a : u8\n    out y : u8\n    y = a\n}\n";
    let file = dir.join("m.volt");
    std::fs::write(&file, src).unwrap();

    let plain = volt()
        .args(["build", "--target-dir"])
        .arg(dir.join("b1"))
        .arg(&file)
        .env_remove("VOLT_LANG")
        .output()
        .unwrap();
    let stderr = String::from_utf8_lossy(&plain.stderr);
    assert_eq!(plain.status.code(), Some(0), "{stderr}");
    assert!(
        !stderr.contains("W0022"),
        "SDC istenmeden W0022 yok: {stderr}"
    );

    let with_sdc = volt()
        .args(["build", "--target-dir"])
        .arg(dir.join("b2"))
        .arg("--emit=sdc")
        .arg(&file)
        .env_remove("VOLT_LANG")
        .output()
        .unwrap();
    let stderr = String::from_utf8_lossy(&with_sdc.stderr);
    assert_eq!(with_sdc.status.code(), Some(0), "{stderr}");
    assert!(stderr.contains("warning[W0022]"), "{stderr}");
    assert!(
        stderr.contains("domain 'Sys' has no frequency; no create_clock emitted for 'clk'"),
        "{stderr}"
    );
    assert!(
        stderr.contains("= help:") && stderr.contains("frequency = 100.mhz"),
        "{stderr}"
    );
    let sdc = read(&dir.join("b2/constraints/M.sdc"));
    assert!(!sdc.lines().any(|l| l.starts_with("create_clock")), "{sdc}");
    assert!(sdc.contains("no create_clock (W0022)"), "{sdc}");
    let _ = std::fs::remove_dir_all(&dir);
}

