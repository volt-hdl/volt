//! `volt build --emit=sdc,xdc` (ADR-0054): kısıt dosyalarının yeri,
//! içeriği (create_clock periyodu, set_clock_groups, sync() false path),
//! W0022'nin yalnız istek üzerine verilmesi, E0017 ve JSON artifacts.

use std::path::{Path, PathBuf};
use std::process::Command;

fn volt() -> Command {
    Command::new(env!("CARGO_BIN_EXE_volt"))
}

fn root() -> PathBuf {
    PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."))
}

fn ui(rel: &str) -> PathBuf {
    root().join("tests/ui").join(rel)
}

fn temp_dir(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("volt-sdc-test-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("temp dizini");
    dir
}

fn build(tag: &str, source: &Path, kinds: &str) -> (PathBuf, std::process::Output) {
    let target = temp_dir(tag);
    let output = volt()
        .args(["build", "--target-dir"])
        .arg(&target)
        .arg(format!("--emit={kinds}"))
        .arg(source)
        .env_remove("VOLT_LANG")
        .output()
        .expect("volt çalışmalı");
    (target, output)
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{} okunmalı: {e}", path.display()))
}

#[test]
fn single_clock_sdc_has_create_clock_with_period_20_000() {
    let (target, out) = build("single", &ui("pass/73_sdc_single_clock.volt"), "sdc");
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "stderr: {stderr}");
    let sdc = read(&target.join("constraints/Uart.sdc"));
    assert!(sdc.starts_with("# Generated by Volt "), "{sdc}");
    assert!(
        sdc.contains("# Source: 73_sdc_single_clock.volt\n# DO NOT EDIT\n"),
        "{sdc}"
    );
    assert!(
        sdc.contains("create_clock -name clk -period 20.000 [get_ports clk]"),
        "{sdc}"
    );
    assert!(!sdc.contains("set_clock_groups"), "{sdc}");
    assert!(
        sdc.contains("set_false_path -from [get_cells {cfg_r_reg*}] -to [get_ports sample]"),
        "{sdc}"
    );
    assert!(stderr.contains("Uart.sdc"), "Output satırı: {stderr}");
    assert!(!stderr.contains("W0022"), "frekans var: {stderr}");
    assert!(!target.join("constraints/Uart.xdc").exists());
    let _ = std::fs::remove_dir_all(&target);
}

#[test]
fn multi_clock_sdc_has_two_clocks_groups_and_bridge_false_paths() {
    let (target, out) = build("multi", &ui("pass/74_sdc_multi_clock.volt"), "sdc,xdc");
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert_eq!(out.status.code(), Some(0), "stderr: {stderr}");
    let sdc = read(&target.join("constraints/Bridge.sdc"));
    assert!(
        sdc.contains("create_clock -name fast_clk -period 10.000 [get_ports fast_clk]"),
        "{sdc}"
    );
    assert!(
        sdc.contains("create_clock -name slow_clk -period 39.722 [get_ports slow_clk]"),
        "{sdc}"
    );
    assert!(sdc.contains("set_clock_groups -asynchronous \\\n    -group [get_clocks {fast_clk}] \\\n    -group [get_clocks {slow_clk}]"), "{sdc}");
    assert!(
        sdc.contains(
            "set_false_path -from [get_cells {go_r_reg*}] -to [get_cells {sync_go_r_stage0_reg*}]"
        ),
        "{sdc}"
    );
    assert!(
        sdc.contains(
            "set_false_path -from [get_cells {ps_toggle_reg*}] -to [get_cells {ps_sync0_reg*}]"
        ),
        "{sdc}"
    );
    assert!(
        sdc.contains("set_multicycle_path 2 -setup -to [get_cells {acc_r_reg*}]"),
        "{sdc}"
    );
    assert!(
        sdc.contains("set_multicycle_path 1 -hold -to [get_cells {acc_r_reg*}]"),
        "{sdc}"
    );
    assert!(!sdc.contains("ASYNC_REG"));
    let xdc = read(&target.join("constraints/Bridge.xdc"));
    assert!(
        xdc.contains(
            "set_property ASYNC_REG TRUE [get_cells {sync_go_r_stage0_reg* sync_go_r_stage1_reg*}]"
        ),
        "{xdc}"
    );
    assert!(
        xdc.contains(
            "set_property ASYNC_REG TRUE [get_cells {ps_sync0_reg* ps_sync1_reg* ps_sync2_reg*}]"
        ),
        "{xdc}"
    );
    let _ = std::fs::remove_dir_all(&target);
}

