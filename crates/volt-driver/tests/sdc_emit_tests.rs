#[test]
fn json_artifacts_list_constraint_files_after_rtl() {
    let target = temp_dir("json");
    let out = volt()
        .args(["build", "--format", "json", "--target-dir"])
        .arg(&target)
        .arg("--emit=sdc,xdc,sdc")
        .arg(ui("pass/73_sdc_single_clock.volt"))
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(0));
    let v: serde_json::Value = serde_json::from_slice(&out.stdout).expect("JSON zarfı");
    let artifacts: Vec<String> = v["artifacts"]
        .as_array()
        .unwrap()
        .iter()
        .map(|a| a.as_str().unwrap().to_string())
        .collect();
    assert_eq!(artifacts.len(), 3, "{artifacts:?} — yinelenen sdc bir kez");
    assert!(artifacts[0].ends_with("Uart.sv"));
    assert!(artifacts[1].ends_with("Uart.sdc"));
    assert!(artifacts[2].ends_with("Uart.xdc"));
    let _ = std::fs::remove_dir_all(&target);
}

#[test]
fn explain_e0017_and_w0022_in_both_languages() {
    for (code, lang, needle) in [
        ("E0017", "en", "Supported forms"),
        ("E0017", "tr", "Desteklenen biçimler"),
        ("W0022", "en", "create_clock needs a period"),
        ("W0022", "tr", "create_clock bir periyot ister"),
    ] {
        let out = volt()
            .args(["explain", code])
            .env("VOLT_LANG", lang)
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&out.stdout);
        assert_eq!(out.status.code(), Some(0), "{code} {lang}");
        assert!(stdout.contains(needle), "{code} {lang}: {stdout}");
    }
}
