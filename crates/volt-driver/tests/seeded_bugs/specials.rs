//! Design-specific mutations: hazards that need more than a pattern to
//! write (a leak through a function, a second reset synchronizer in a
//! child), each with its near-miss twin where one exists. Every `find`
//! must occur exactly once in the design; when a design changes so that
//! it does not, the test fails and names the mutation.

pub struct Special {
    pub kind: &'static str,
    pub design: &'static str,
    pub site: &'static str,
    pub edits: &'static [(&'static str, &'static str)],
    /// Expected codes (hazard) or allowed codes (near miss).
    pub codes: &'static [&'static str],
    pub near_miss: bool,
    /// The specification rule behind `codes`.
    pub spec: &'static str,
}

